import gradio as gr

def chatbot(image, question):
    if image is None:
        return "Please upload an image first!"

    if question.strip() == "":
        return "Please enter a question!"

    results = model(image, top_k=5)

    answer = "Here are the top predictions:\n"

    for result in results:
        label = result["label"]
        confidence = result["score"] * 100
        answer += f"\n{label}: {confidence:.2f}%"

    return answer

demo = gr.Interface(
    fn=chatbot,
    inputs=[
        gr.Image(type="pil", label="Upload an Image"),
        gr.Textbox(label="Ask a Question", placeholder="What is in this image?")
    ],
    outputs=gr.Textbox(label="Chatbot Response"),
    title="🤖 My Image Chatbot",
    description="Upload an image and ask a question."
)

demo.launch(share=True)